--- port from https://github.com/goolord/alpha-nvim
local F
local alpha_buf
local autocmd = vim.api.nvim_create_autocmd
local augroup = vim.api.nvim_create_augroup

local alpha_close = function()
	vim.api.nvim_buf_delete(alpha_buf, {})
	alpha_buf = nil
end

local should_skip_alpha = function()
	-- don't start when opening a file
	if vim.fn.argc() > 0 then
		return true
	end

	-- WARN: bug! don't start when restart
	if vim.v.startreason ~= "normal" then
		return true
	end

	-- Do not open alpha if the current buffer has any lines (something opened explicitly).
	local lines = vim.api.nvim_buf_get_lines(0, 0, 2, false)
	if #lines > 1 or (#lines == 1 and lines[1]:len() > 0) then
		return true
	end

	-- Skip when there are other listed buffers in windows(diff).
	local curr_buf = vim.api.nvim_get_current_buf()
	for _, win in ipairs(vim.api.nvim_list_wins()) do
		local buf = vim.api.nvim_win_get_buf(win)
		if buf ~= curr_buf and vim.bo[buf].buflisted then
			return true
		end
	end

	-- Handle nvim -M
	if not vim.o.modifiable then
		return true
	end

	for _, arg in ipairs(vim.v.argv) do
		-- whitelisted arguments
		-- always open
		if arg == "--startuptime" then
			return false
		end

		-- blacklisted arguments
		-- always skip
		if
			arg == "-b"
			-- commands, typically used for scripting
			or arg == "-c"
			or vim.startswith(arg, "+")
			or arg == "-S"
		then
			return true
		end
	end

	-- base case: don't skip
	return false
end

local function render()
	if alpha_buf == nil then
		return
	end
	local win = vim.api.nvim_get_current_win()
	local width = vim.api.nvim_win_get_width(win)
	local height = vim.api.nvim_win_get_height(win)
	local art_width = vim.fn.strdisplaywidth(F.art[1])
	local left = math.max(0, math.floor((width - art_width) / 2))
	local top = math.max(0, math.floor((height - #F.art) / 2) + F.offset)
	local lines = {}
	for _ = 1, top do
		lines[#lines + 1] = ""
	end
	for _, line in ipairs(F.art) do
		lines[#lines + 1] = string.rep(" ", left) .. line
	end

	vim.bo[alpha_buf].modifiable = true
	vim.bo[alpha_buf].readonly = true
	vim.api.nvim_buf_set_lines(alpha_buf, 0, -1, false, lines)
	local alpha_highlight = vim.api.nvim_create_namespace("alpha_highlight")
	vim.hl.range(alpha_buf, alpha_highlight, "Alpha", { 0, 0 }, { 999, 999 })
	vim.bo[alpha_buf].modifiable = false
	vim.bo[alpha_buf].readonly = false
end

local enable_alpha = function()
	local eventignore = vim.o.eventignore
	vim.o.eventignore = "all"

	local set = function(opt, val)
		vim.api.nvim_set_option_value(opt, val, { scope = "local" })
	end
	set("bufhidden", "wipe")
	set("buflisted", false)
	set("matchpairs", "")
	set("swapfile", false)
	set("buftype", "nofile")
	set("filetype", "alpha")
	set("synmaxcol", 0)
	set("wrap", false)
	set("colorcolumn", "")
	set("foldlevel", 999)
	set("foldcolumn", "0")
	set("cursorcolumn", false)
	set("cursorline", false)
	set("number", false)
	set("relativenumber", false)
	set("list", false)
	set("spell", false)
	set("signcolumn", "no")

	vim.o.eventignore = eventignore

	autocmd("SessionLoadPost", {
		group = augroup("matsu.alpha.close", { clear = true }),
		callback = alpha_close,
	})

	local resize_id = augroup("matsu.alpha.resized", { clear = true })
	autocmd("VimResized", {
		group = resize_id,
		buffer = alpha_buf,
		callback = render,
	})
	autocmd("WinEnter", {
		group = resize_id,
		buffer = alpha_buf,
		callback = render,
	})

	vim.keymap.set("n", "e", function()
		vim.cmd.enew()
	end, { buffer = alpha_buf, desc = "New empty file" })
end

local alpha_start = function()
	if should_skip_alpha() then
		return
	end

	local window = vim.api.nvim_get_current_win()
	local buf = vim.api.nvim_win_get_buf(window)

	if vim.bo[buf].ft == "alpha" then
		return
	end

	alpha_buf = vim.api.nvim_create_buf(false, true)
	vim.api.nvim_win_set_buf(window, alpha_buf)
	vim.api.nvim_buf_delete(buf, {})

	enable_alpha()
	render()
end

autocmd("VimEnter", {
	group = augroup("matsu.alpha_start", { clear = true }),
	pattern = "*",
	nested = true,
	callback = function()
		alpha_start()
	end,
})

